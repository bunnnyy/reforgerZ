"""Helpers for the runtime test's site audit (tools/runtime_test/run.sh; docs/SITES.md, "The audit").

    python3 sites.py prepare <addon dir> <world .ent> ...   # camp life's kits and Traces' kit into the test worlds, the props list
    python3 sites.py footprints <console.log> <out.json>    # the measured prop boxes as footprints.json
    python3 sites.py summary <console.log>                  # the audit's lines, for run.sh to print

Nothing here is part of the mod: it edits only the throwaway addon copy.
"""
import json, os, re, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.normpath(os.path.join(HERE, "..", ".."))
GM = os.path.join(REPO, "Prefabs/ReforgerZ/Core/RZ_GameMode.et")
PROPS = os.path.join(REPO, "tools/camp_kit/props.txt")


def camp_block(field="m_CampLifeSettings RZ_CampLifeSettings"):
    """Territory > Camp life as RZ_GameMode.et has it (the kits, the waypoints); with `field`, another
    settings block (World > Traces: its kit, the prefabs a site's story names)."""
    text = open(GM, encoding="utf-8", newline="").read().replace("\r\n", "\n")
    start = text.index("   " + field + " ")
    depth = 0
    i = text.index('" {', start) + 2
    while True:
        if text[i] == "{":
            depth += 1
        elif text[i] == "}":
            depth -= 1
            if depth == 0:
                break
        i += 1
    return text[start:i + 1]


def prepare(addon, worlds):
    block = camp_block() + "\n" + camp_block("m_TraceSettings RZ_TraceSettings")
    for world in worlds:
        path = os.path.join(addon, world)
        text = open(path, encoding="utf-8").read()
        if "m_CampLifeSettings" in text:
            continue
        anchor = re.search(r'  RZ_GameModeComponent "\{[0-9A-F]+\}" \{\n', text)
        text = text[:anchor.end()] + block + "\n" + text[anchor.end():]
        open(path, "w", encoding="utf-8").write(text)
    names = []
    for line in open(PROPS, encoding="utf-8"):
        bits = line.strip().split(" ")
        if len(bits) >= 2 and not line.startswith("#"):
            names.append(bits[1])
    out = ["// Generated by tools/runtime_test/sites.py: the camp kit's props (tools/camp_kit/props.txt).",
           "class RZS_Props", "{", "\tprotected static ref array<ResourceName> s_aList;", "",
           "\tstatic array<ResourceName> List()", "\t{", "\t\tif (s_aList)", "\t\t\treturn s_aList;", "", "\t\ts_aList = {};"]
    out += ['\t\ts_aList.Insert("%s");' % n for n in names]
    out += ["\t\treturn s_aList;", "\t}", "}", ""]
    folder = os.path.join(addon, "scripts/Game/RZSites")
    os.makedirs(folder, exist_ok=True)
    open(os.path.join(folder, "RZS_Props.c"), "w", encoding="utf-8").write("\n".join(out))


def footprints(log, out):
    props = {}
    for line in open(log, encoding="utf-8", errors="replace"):
        m = re.search(r"RZS footprint (\S+\.et) (\S+) (\S+) (\S+) (\S+) (\S+) (\S+)", line)
        if not m:
            continue
        name = m.group(1)
        w, d, h, ox, oz, base = (float(v) for v in m.groups()[1:])
        if w < 0.01 and d < 0.01:
            continue
        props[name] = {"w": round(w, 3), "d": round(d, 3), "h": round(h, 3), "ox": round(ox, 3), "oz": round(oz, 3), "feet": abs(base) < 0.1}
    data = {"version": 1, "source": "tools/runtime_test/run.sh sites (the dedicated server's boxes; the Workbench plugin ReforgerZ: Measure prop footprints writes the same)", "props": dict(sorted(props.items()))}
    with open(out, "w", encoding="utf-8") as f:
        json.dump(data, f, indent=1)
        f.write("\n")
    return len(props)


def summary(log):
    keep = ("[ReforgerZ] Sites audit", "[ReforgerZ] Sites:", "[ReforgerZ] Sites people:", "[ReforgerZ] Sites story:", "RZS done", "RZS footprint missing", "RZS footprint failed", "RZS land ready", "RZS audit:", "RZS roll")
    for line in open(log, encoding="utf-8", errors="replace"):
        if any(k in line for k in keep):
            i = line.find("Sites")
            j = line.find("RZS")
            at = min(x for x in (i, j) if x >= 0)
            print("  " + line[at:].rstrip())


if __name__ == "__main__":
    cmd = sys.argv[1]
    if cmd == "prepare":
        prepare(sys.argv[2], sys.argv[3:])
    elif cmd == "footprints":
        print(footprints(sys.argv[2], sys.argv[3]))
    elif cmd == "summary":
        summary(sys.argv[2])
    else:
        sys.exit(__doc__)
